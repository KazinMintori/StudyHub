import {readFile,writeFile} from 'node:fs/promises'
const root=new URL('../../',import.meta.url)
const specs={local:['landscapeSteps','queenSteps','twoOptSteps','geneticSteps'],csp:['ac3Steps','backtrackingSteps','treeCspSteps']}
const code={}
for(const [group,names]of Object.entries(specs)){
 const file=group==='local'?'local-search.mjs':'csp-search.mjs'
 const source=await readFile(new URL('src/features/labs/services/'+file,root),'utf8')
 for(const name of names){const start=source.indexOf('export function* '+name+'('),end=source.indexOf('\nexport ',start+1);if(start<0)throw Error(name);code[name]=source.slice(start,end<0?undefined:end).trim().split('\n')}
}
await writeFile(new URL('src/features/labs/services/local-csp-code.mjs',root),'// Generated by scripts/content/sync-local-csp-code.mjs.\nexport const code = '+JSON.stringify(code,null,2)+'\n')
console.log('Synchronized seven executed generator listings')
