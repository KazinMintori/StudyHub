import assert from 'node:assert/strict'
import {readFile,writeFile,mkdir} from 'node:fs/promises'
import puppeteer from 'puppeteer'
const base=process.env.QA_URL||'http://127.0.0.1:5187'
const output='qa/data-exam/interactions'
await mkdir(output,{recursive:true})
const browser=await puppeteer.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const checks=[]
try{
 const page=await browser.newPage()
 await page.setViewport({width:375,height:900})
 await page.evaluateOnNewDocument(()=>{
  sessionStorage.setItem('studyhub_welcome_seen','1')
  Object.defineProperty(navigator,'clipboard',{value:{writeText:async value=>{window.__copiedCode=value}}})
 })
 const goto=async(lesson,query='')=>{
  await page.goto(`${base}/xu-ly-du-lieu/on-thi/bai-${lesson}.html${query}`,{waitUntil:'networkidle2'})
  await page.waitForSelector('.exam-question__id-tag')
 }
 await goto('03')
 await page.evaluate(()=>sessionStorage.removeItem('studyhub_exam_session_lesson_03'))
 await page.reload({waitUntil:'networkidle2'})
 await page.focus('.exam-choice__radio')
 await page.keyboard.press('ArrowDown')
 assert.equal(await page.evaluate(()=>document.activeElement.value),'B')
 assert.equal(await page.$$eval('.exam-choice__explanation',n=>n.length),0)
 await page.keyboard.press('Enter')
 await page.waitForSelector('.exam-choice__explanation')
 assert.equal(await page.$$eval('.exam-choice__explanation',n=>n.length),4)
 assert.equal(await page.$eval('.exam-score-badge--correct',n=>n.textContent.trim()),'1')
 checks.push('Keyboard radio focus, explicit submission, all four explanations and correct score')
 await page.click('.exam-nav-btn--next')
 await page.waitForFunction(()=>document.querySelector('.exam-question__id-tag').textContent.trim()==='B3-002')
 await page.$eval('.exam-choice__html code',n=>n.click())
 await page.waitForSelector('.exam-choice__explanation')
 assert.equal(await page.$eval('.exam-score-badge--wrong',n=>n.textContent.trim()),'1')
 await page.reload({waitUntil:'networkidle2'})
 assert.equal(await page.$eval('.exam-score-badge--correct',n=>n.textContent.trim()),'1')
 assert.equal(await page.$eval('.exam-score-badge--wrong',n=>n.textContent.trim()),'1')
 checks.push('Inline-code option can be selected; score and answers survive reload')
 const expected=await page.$eval('.exam-question__prompt pre code',n=>n.textContent)
 await page.$eval('.exam-question__prompt button.copy',n=>n.click())
 await page.waitForFunction(()=>typeof window.__copiedCode==='string')
 assert.equal(await page.evaluate(()=>window.__copiedCode),expected)
 checks.push('Copy code preserves exact text and indentation')
 await page.click('.exam-jump-trigger')
 await page.waitForSelector('.exam-modal__close-btn')
 assert(await page.evaluate(()=>document.activeElement.classList.contains('exam-modal__close-btn')))
 await page.keyboard.down('Shift');await page.keyboard.press('Tab');await page.keyboard.up('Shift')
 assert(await page.evaluate(()=>document.activeElement===document.querySelector('.exam-modal__cell:last-child')))
 await page.keyboard.press('Tab')
 assert(await page.evaluate(()=>document.activeElement.classList.contains('exam-modal__close-btn')))
 await page.keyboard.press('Escape')
 assert.equal(await page.$('.exam-modal-backdrop'),null)
 assert(await page.evaluate(()=>document.activeElement.classList.contains('exam-jump-trigger')))
 checks.push('Question modal traps Tab/Shift+Tab; Escape restores trigger focus')
 await page.click('.exam-jump-trigger')
 const lastId=await page.$eval('.exam-modal__cell:last-child .exam-modal__cell-id',n=>n.textContent.trim())
 await page.click('.exam-modal__cell:last-child')
 await page.waitForFunction(id=>document.querySelector('.exam-question__id-tag').textContent.trim()===id,{},lastId)
 assert(await page.$eval('.exam-nav-btn--next',n=>n.disabled))
 checks.push('Question picker reaches final extension question and disables next')
 await page.$eval('.exam-mode-switch__btn:nth-child(2)',n=>n.click())
 assert.equal(await page.$eval('.exam-essay__details',n=>n.open),false)
 await page.click('.exam-essay__details > summary')
 assert.equal(await page.$eval('.exam-essay__details',n=>n.open),true)
 await page.click('.exam-nav-btn--next')
 assert.equal(await page.$eval('.exam-essay__details',n=>n.open),false)
 checks.push('Essay answer opens on request and resets closed for next essay')
 await goto('07','?mode=quiz&cau=B7-R01')
 assert.equal(await page.$eval('.exam-question__id-tag',n=>n.textContent.trim()),'B7-R01')
 await page.screenshot({path:`${output}/regex-375.png`})
 await goto('03','?mode=invalid&cau=missing')
 assert.equal(await page.$eval('.exam-question__id-tag',n=>n.textContent.trim()),'B3-001')
 checks.push('Direct regex deep link and invalid-query fallback')
 await goto('07','?mode=quiz&cau=B7-044')
 const currencyText=await page.$eval('.exam-question__prompt',node=>node.textContent)
 for(const value of ["0=' $0.00 '","1='$-5.00'","2='$25.5'","3='$25'"]) assert(currencyText.includes(value),`Currency text preserved: ${value}`)
 await goto('07','?mode=essay&cau=B7-059')
 const htmlText=await page.$eval('.exam-question__prompt',node=>node.textContent)
 for(const value of ['<br/>','<br>','<BR/>']) assert(htmlText.includes(value),`Literal HTML preserved: ${value}`)
 await page.click('.exam-essay__details > summary')
 assert((await page.$eval('.exam-essay__answer',node=>node.textContent)).includes('<b>Z</b>'))
 assert.equal(await page.$('.exam-assumptions'),null)
 await goto('04','?mode=quiz&cau=B4-045')
 assert((await page.$eval('.exam-question__prompt',node=>node.textContent)).startsWith('Dùng pandas 3.x với Copy-on-Write.'))
 checks.push('No general assumptions panel; material condition appears in question; currency text is complete')
 await goto('03','?mode=quiz&cau=B3-001')
 for(const width of [375,768,1280]){
  await page.setViewport({width,height:900})
  for(const dark of [true,false]){
   await page.evaluate(on=>document.documentElement.classList.toggle('dark',on),dark)
   await page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))))
   const box=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,width:innerWidth}))
   assert(box.doc<=box.width+1)
   const center=await page.$eval('.exam-practice',node=>{const rect=node.getBoundingClientRect();return (rect.left+rect.right)/2})
   assert(Math.abs(center-width/2)<2,'Quiz centered in the viewport')
   await page.screenshot({path:`${output}/feedback-${width}-${dark?'dark':'light'}.png`})
  }
 }
 checks.push('Feedback at375,768,1280 in light/dark has no page overflow')
 console.log(`PASS ${checks.length} interactive exam scenarios`)
}finally{await browser.close();await writeFile(`${output}/report.json`,JSON.stringify(checks,null,2)+'\n')}
